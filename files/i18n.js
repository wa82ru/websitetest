// =============================================
//  言語切り替え処理
// =============================================

function applyLang(lang) {
  const t = I18N[lang];
  if (!t) return;

  // data-i18n属性を持つ要素を一括更新（ヘッダー注入後も確実に動くよう全DOM対象）
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) {
      el.innerHTML = t[key];
      // サブテキストは空なら非表示
      if (key === 'header.logo.sub') {
        el.style.display = t[key] === '' ? 'none' : 'block';
      }
    }
  });

  // html lang属性更新
  document.documentElement.lang = lang === 'ja' ? 'ja' : lang === 'zh' ? 'zh' : lang === 'ko' ? 'ko' : 'en';

  // 選択言語を保存
  localStorage.setItem('yk_lang', lang);

  // ボタンのアクティブ状態更新
  document.querySelectorAll('.lang-btn-item').forEach(btn => {
    btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
  });
}

function initI18n() {
  const saved = localStorage.getItem('yk_lang') || 'ja';
  applyLang(saved);
}

